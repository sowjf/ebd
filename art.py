"""ASCII art: monsters, scenes, title. Sections are '## name' followed by raw art lines."""


def _parse(text):
    out, cur = {}, None
    for line in text.split("\n"):
        if line.startswith("## "):
            cur = line[3:].strip()
            out[cur] = []
        elif cur is not None:
            out[cur].append(line)
    for k in out:
        while out[k] and not out[k][-1].strip():
            out[k].pop()
    return out


